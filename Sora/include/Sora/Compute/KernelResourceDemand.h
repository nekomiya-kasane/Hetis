/**
 * @file KernelResourceDemand.h
 * @brief Device-independent per-work-item resource demand for portable kernel planning.
 * @ingroup Compute
 */
#pragma once

#include <Sora/Compute/KernelIR.h>

#include <cstdint>
#include <limits>
#include <type_traits>

namespace Sora::Compute {

    namespace Detail {

        [[nodiscard]] constexpr uint64_t SaturatingDemandAdd(uint64_t left, uint64_t right) noexcept {
            return right > std::numeric_limits<uint64_t>::max() - left ? std::numeric_limits<uint64_t>::max()
                                                                       : left + right;
        }

        [[nodiscard]] constexpr uint64_t SaturatingDemandMultiply(uint64_t left, uint64_t right) noexcept {
            return left != 0 && right > std::numeric_limits<uint64_t>::max() / left
                       ? std::numeric_limits<uint64_t>::max()
                       : left * right;
        }

    } // namespace Detail

    /** @brief Canonical device-independent demand generated by one logical work item. */
    struct KernelResourceDemand {
        uint64_t integerOperations = 0;
        uint64_t floatingPointOperations = 0;
        uint64_t float64Operations = 0;
        uint64_t specialFunctionOperations = 0;
        uint64_t bytesRead = 0;
        uint64_t bytesWritten = 0;
        uint64_t stridedBytesRead = 0;
        uint64_t stridedBytesWritten = 0;
        uint64_t synchronizationOperations = 0;

        /** @brief Return total logical memory traffic per work item with saturating arithmetic. */
        [[nodiscard]] constexpr uint64_t MemoryBytes() const noexcept {
            return Detail::SaturatingDemandAdd(bytesRead, bytesWritten);
        }

        /** @brief Return the subset of logical traffic issued through actual strided bindings. */
        [[nodiscard]] constexpr uint64_t StridedMemoryBytes() const noexcept {
            return Detail::SaturatingDemandAdd(stridedBytesRead, stridedBytesWritten);
        }

        /** @brief Mark one actual strided buffer access without changing total logical traffic. */
        constexpr void AddStridedMemory(AccessMode access, uint64_t bytes) noexcept {
            if (access != AccessMode::Write) {
                stridedBytesRead = Detail::SaturatingDemandAdd(stridedBytesRead, bytes);
            }
            if (access != AccessMode::Read) {
                stridedBytesWritten = Detail::SaturatingDemandAdd(stridedBytesWritten, bytes);
            }
        }

        /** @brief Return whether all subsets are bounded by their totals and at least one resource is demanded. */
        [[nodiscard]] constexpr bool Valid() const noexcept {
            const bool nonempty = integerOperations != 0 || floatingPointOperations != 0 || float64Operations != 0 ||
                                  specialFunctionOperations != 0 || bytesRead != 0 || bytesWritten != 0 ||
                                  synchronizationOperations != 0;
            return nonempty && stridedBytesRead <= bytesRead && stridedBytesWritten <= bytesWritten;
        }

        friend constexpr bool operator==(KernelResourceDemand, KernelResourceDemand) noexcept = default;
    };

    static_assert(std::is_trivially_copyable_v<KernelResourceDemand>);
    static_assert(std::is_standard_layout_v<KernelResourceDemand>);

} // namespace Sora::Compute
